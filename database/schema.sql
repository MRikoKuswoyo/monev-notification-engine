-- ---------- TABEL ----------

create table if not exists public.users (
  id                integer generated by default as identity primary key,
  name              varchar(100) not null,
  email             varchar(120) not null unique,
  division          varchar(100),
  telegram_chat_id  varchar(30),
  created_at        timestamptz not null default now()
);

-- Waktu (check_in_at, check_out_at, created_at) disimpan sebagai timestamptz (UTC);
-- work_date = tanggal kerja WIB
create table if not exists public.attendances (
  id            integer generated by default as identity primary key,
  user_id       integer not null references public.users(id) on delete cascade,
  work_date     date not null,
  check_in_at   timestamptz,
  check_out_at  timestamptz,
  constraint uq_att unique (user_id, work_date)
);

create table if not exists public.logbooks (
  id          integer generated by default as identity primary key,
  user_id     integer not null references public.users(id) on delete cascade,
  work_date   date not null,
  content     text not null,
  created_at  timestamptz not null,
  constraint uq_log unique (user_id, work_date)
);

create table if not exists public.notifications (
  id             integer generated by default as identity primary key,
  user_id        integer not null references public.users(id) on delete cascade,
  work_date      date not null,
  category       varchar(20) not null,
  title          varchar(150) not null,
  message        varchar(255) not null,
  action_button  varchar(60) not null,
  is_read        boolean not null default false,
  created_at     timestamptz not null,
  constraint uq_notif unique (user_id, category, work_date)
);

create index if not exists idx_att_user   on public.attendances (user_id);
create index if not exists idx_log_user   on public.logbooks (user_id);
create index if not exists idx_notif_user on public.notifications (user_id, is_read);

-- ---------- KEAMANAN (RLS) ----------
-- Tabel di schema "public" otomatis bisa diakses lewat API Supabase.
-- RLS diaktifkan tanpa policy = anon/authenticated key TIDAK bisa baca/tulis.
-- Backend (service_role key) tetap bisa akses karena melewati RLS.
alter table public.users          enable row level security;
alter table public.attendances    enable row level security;
alter table public.logbooks       enable row level security;
alter table public.notifications  enable row level security;

-- ---------- DATA CONTOH (opsional, setara scripts/setup-db.js) ----------
-- 5 peserta + riwayat absen/logbook N hari kerja sebelum hari ini (WIB).
-- Hanya jalan jika tabel users masih kosong.
do $$
declare
  p          record;
  uid        integer;
  d          date;
  cnt        integer;
  today_wib  date := (now() at time zone 'Asia/Jakarta')::date;
begin
  if exists (select 1 from public.users) then
    raise notice 'Data sudah ada, seed dilewati';
    return;
  end if;

  for p in
    select * from (values
      ('Riko', 'riko@example.com', 'Teknologi Informasi', 4),  -- streak 5 setelah hari ini selesai
      ('Sari', 'sari@example.com', 'Humas',               2),  -- streak 3
      ('Budi', 'budi@example.com', 'Administrasi',        9),  -- streak 10
      ('Dewi', 'dewi@example.com', 'Keuangan',            0),
      ('Andi', 'andi@example.com', 'Umum',                1)
    ) as t(name, email, division, past)
  loop
    insert into public.users (name, email, division)
    values (p.name, p.email, p.division)
    returning id into uid;

    d := today_wib;
    cnt := 0;
    while cnt < p.past loop
      d := d - 1;
      if extract(isodow from d) between 1 and 5 then   -- Senin–Jumat
        insert into public.attendances (user_id, work_date, check_in_at, check_out_at)
        values (uid, d,
                (d + time '08:05') at time zone 'Asia/Jakarta',
                (d + time '16:45') at time zone 'Asia/Jakarta');
        insert into public.logbooks (user_id, work_date, content, created_at)
        values (uid, d,
                'Mengerjakan tugas harian, rapat koordinasi, dan dokumentasi kegiatan.',
                (d + time '16:00') at time zone 'Asia/Jakarta');
        cnt := cnt + 1;
      end if;
    end loop;
  end loop;
end $$;
